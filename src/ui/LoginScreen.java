    private void cmbSuppliersActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_cmbSuppliersActionPerformed
        // TODO add your handling code here:
         // Get the role selected by the user
    String selectedRole = (String) cmbRoles.getSelectedItem();

    // Check whether the Administrator role was selected
    if ("Administrator".equals(selectedRole)) {

        // Create the Administrator dashboard
        AdminWorkAreaJPanel adminPanel =
                new AdminWorkAreaJPanel(
                        mainWorkArea, supplierDirectory);

        // Add the dashboard to the main work area
        mainWorkArea.add("AdminWorkAreaJPanel", adminPanel);

        // Display the Administrator dashboard
        CardLayout layout =
                (CardLayout) mainWorkArea.getLayout();

        layout.show(mainWorkArea, "AdminWorkAreaJPanel");

    } else if ("Supplier".equals(selectedRole)) {

        // Retrieve the selected supplier
        Supplier selectedSupplier =
                (Supplier) cmbSuppliers.getSelectedItem();

        // Make sure a supplier has been selected
        if (selectedSupplier == null) {

            JOptionPane.showMessageDialog(
                    this,
                    "Please select a supplier before logging in.",
                    "Login Error",
                    JOptionPane.ERROR_MESSAGE);

            return;
        }

        // Create the Supplier dashboard
        SupplierWorkAreaJPanel supplierPanel =
                new SupplierWorkAreaJPanel(
                        mainWorkArea, selectedSupplier);

        // Add the dashboard to the main work area
        mainWorkArea.add("SupplierWorkAreaJPanel", supplierPanel);

        // Display the Supplier dashboard
        CardLayout layout =
                (CardLayout) mainWorkArea.getLayout();

        layout.show(mainWorkArea, "SupplierWorkAreaJPanel");
    }       
        
    }//GEN-LAST:event_cmbSuppliersActionPerformed

    private void btnLoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLoginActionPerformed
        // TODO add your handling code here:
         // Get the selected account role
    String selectedRole = (String) cmbRoles.getSelectedItem();

    if ("Administrator".equals(selectedRole)) {

        // Open the Administrator dashboard
        AdminWorkAreaJPanel adminPanel =
                new AdminWorkAreaJPanel(
                        mainWorkArea, supplierDirectory);

        mainWorkArea.add("AdminWorkAreaJPanel", adminPanel);

        CardLayout layout =
                (CardLayout) mainWorkArea.getLayout();

        layout.show(mainWorkArea, "AdminWorkAreaJPanel");

    } else if ("Supplier".equals(selectedRole)) {

        // Get the selected supplier
        Supplier selectedSupplier =
                (Supplier) cmbSuppliers.getSelectedItem();

        if (selectedSupplier == null) {
            JOptionPane.showMessageDialog(
                    this,
                    "Please select a supplier.",
                    "Login Error",
                    JOptionPane.WARNING_MESSAGE);
            return;
        }

        // Open the Supplier dashboard
        SupplierWorkAreaJPanel supplierPanel =
                new SupplierWorkAreaJPanel(
                        mainWorkArea, selectedSupplier);

        mainWorkArea.add("SupplierWorkAreaJPanel", supplierPanel);

        CardLayout layout =
                (CardLayout) mainWorkArea.getLayout();

        layout.show(mainWorkArea, "SupplierWorkAreaJPanel");
    }
             
    }//GEN-LAST:event_btnLoginActionPerformed

