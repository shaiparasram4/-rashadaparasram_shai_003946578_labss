    private void populateRoleCombo() {
        // Clear any options to make duplicates.
      cmbRoles.removeAllItems();
       // Add's two available roles for the user.
      cmbRoles.addItem("Administrator");
      cmbRoles.addItem("Supplier");
      // Set Administrator as the default selected role.
      cmbRoles.setSelectedIndex(0);
    }

    public void populateSupplierCombo() {
        // Clear existing suppliers to avoid duplicates
    cmbSuppliers.removeAllItems();

    // Retrieve suppliers from the supplier directory
    for (Supplier supplier : supplierDirectory.getSupplierList()) {

        // Add each supplier to the dropdown menu
        cmbSuppliers.addItem(supplier);
    }   
  }

    private void updateSupplierVisibility() {
      // Check which role the user selected
    String role = (String) cmbRoles.getSelectedItem();

    // Show supplier options only for Supplier role
    boolean isSupplier = "Supplier".equals(role);

    lblSupplier.setVisible(isSupplier);
    cmbSuppliers.setVisible(isSupplier);   
    }
