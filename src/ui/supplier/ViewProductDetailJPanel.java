    private void backAction() {
          // Remove the current Product Details panel
    workArea.remove(this);

    // Refresh any remaining Product Catalog panels
    for (Component component : workArea.getComponents()) {

        if (component instanceof ManageProductCatalogJPanel) {

            ManageProductCatalogJPanel catalogPanel =
                    (ManageProductCatalogJPanel) component;

            catalogPanel.refreshTable();
        }
    }

    // Return to the previously displayed panel
    CardLayout layout = (CardLayout) workArea.getLayout();
    layout.previous(workArea);
    }
    
    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        // TODO add your handling code here:
         // Retrieve updated product information
    String productName = txtName.getText().trim();
    String priceText = txtPrice.getText().trim();

    // Validate the product name
    if (productName.isEmpty()) {
        JOptionPane.showMessageDialog(
                this,
                "Please enter a product name.",
                "Validation Error",
                JOptionPane.WARNING_MESSAGE);
        return;
    }

    // Validate the product price
    int price;

    try {
        price = Integer.parseInt(priceText);

        if (price < 0) {
            JOptionPane.showMessageDialog(
                    this,
                    "Product price cannot be negative.",
                    "Validation Error",
                    JOptionPane.WARNING_MESSAGE);
            return;
        }

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(
                this,
                "Please enter a valid whole number for the price.",
                "Invalid Price",
                JOptionPane.ERROR_MESSAGE);
        return;
    }

    // Update the existing Product object
    product.setName(productName);
    product.setPrice(price);

    // Disable editing after saving
    txtName.setEditable(false);
    txtPrice.setEditable(false);
    btnSave.setEnabled(false);

    // Confirm successful update
    JOptionPane.showMessageDialog(
            this,
            "Product updated successfully!",
            "Success",
            JOptionPane.INFORMATION_MESSAGE);
        
    }//GEN-LAST:event_btnSaveActionPerformed

