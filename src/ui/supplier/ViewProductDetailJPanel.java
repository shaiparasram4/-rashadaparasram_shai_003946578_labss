    private void btnAddFeatureActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddFeatureActionPerformed
        // TODO add your handling code here:
         // Ask for the feature name
    String featureName = JOptionPane.showInputDialog(
            this, "Enter the feature name:");

    // Stop if the user cancels
    if (featureName == null) {
        return;
    }

    featureName = featureName.trim();

    // Validate the feature name
    if (featureName.isEmpty()) {
        JOptionPane.showMessageDialog(
                this, "Feature name cannot be empty.");
        return;
    }

    // Ask for the feature value
    String featureValue = JOptionPane.showInputDialog(
            this, "Enter the feature value:");

    if (featureValue == null) {
        return;
    }

    featureValue = featureValue.trim();

    // Validate the feature value
    if (featureValue.isEmpty()) {
        JOptionPane.showMessageDialog(
                this, "Feature value cannot be empty.");
        return;
    }

    // Add the feature to the current product
    product.addFeature(featureName, featureValue);

    // Refresh the table to display the new feature
    refreshTable();

    JOptionPane.showMessageDialog(
            this,
            "Product feature added successfully!",
            "Success",
            JOptionPane.INFORMATION_MESSAGE); 
  
    }//GEN-LAST:event_btnAddFeatureActionPerformed

    private void btnRemoveFeatureActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRemoveFeatureActionPerformed
        // TODO add your handling code here:
      // Identify the selected table row
    int selectedRow = tblFeatures.getSelectedRow();

    if (selectedRow < 0) {
        JOptionPane.showMessageDialog(
                this,
                "Please select a feature to remove.",
                "No Feature Selected",
                JOptionPane.WARNING_MESSAGE);
        return;
    }

    // Convert the displayed row to its model index
    int modelRow = tblFeatures.convertRowIndexToModel(
            selectedRow);

    // Find the feature associated with that row
    Feature selectedFeature =
            product.getFeatures().get(modelRow);

    // Confirm the removal
    int confirmation = JOptionPane.showConfirmDialog(
            this,
            "Remove feature: "
                    + selectedFeature.getName() + "?",
            "Confirm Removal",
            JOptionPane.YES_NO_OPTION);

    if (confirmation == JOptionPane.YES_OPTION) {

        // Remove the feature from the product
        product.removeFeature(selectedFeature);

        // Update the displayed feature list
        refreshTable();

        JOptionPane.showMessageDialog(
                this, "Feature removed successfully!");
    }   
    
    }//GEN-LAST:event_btnRemoveFeatureActionPerformed

    public void refreshTable() {
      // Access the feature table model
    DefaultTableModel model =
            (DefaultTableModel) tblFeatures.getModel();

    // Remove existing rows to prevent duplicates
    model.setRowCount(0);

    // Display each feature and its value
    for (Feature feature : product.getFeatures()) {

        Object[] row = new Object[2];

        row[0] = feature.getName();
        row[1] = feature.getValue();

        model.addRow(row);
    }   
        
    }


