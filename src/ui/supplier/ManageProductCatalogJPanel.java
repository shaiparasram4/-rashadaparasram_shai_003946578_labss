    private void btnViewActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnViewActionPerformed
        // TODO add your handling code here:
         // Get the selected row in the product table
    int selectedRow = tblProducts.getSelectedRow();

    // Verify that a product was selected
    if (selectedRow < 0) {
        JOptionPane.showMessageDialog(
                this,
                "Please select a product to view.",
                "No Product Selected",
                JOptionPane.WARNING_MESSAGE);
        return;
    }

    // Retrieve the selected Product object
    Product selectedProduct =
            (Product) tblProducts.getValueAt(selectedRow, 0);

    // Create the product details panel
    ViewProductDetailJPanel detailPanel =
            new ViewProductDetailJPanel(workArea, selectedProduct);

    // Add the details panel to the CardLayout
    workArea.add("ViewProductDetailJPanel", detailPanel);

    // Navigate to the product details screen
    CardLayout layout = (CardLayout) workArea.getLayout();
    layout.next(workArea);
        
    }//GEN-LAST:event_btnViewActionPerformed

