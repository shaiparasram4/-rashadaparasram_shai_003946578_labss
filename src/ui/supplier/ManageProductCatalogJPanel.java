    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        // TODO add your handling code here:
        // Get the selected row from the product table
    int selectedRow = tblProducts.getSelectedRow();

    // Make sure the user selected a product
    if (selectedRow < 0) {
        JOptionPane.showMessageDialog(
                this,
                "Please select a product to delete.",
                "No Product Selected",
                JOptionPane.WARNING_MESSAGE);
        return;
    }

    // Retrieve the selected product object
    Product selectedProduct = (Product)
            tblProducts.getValueAt(selectedRow, 0);

    // Ask the user to confirm deletion
    int confirmation = JOptionPane.showConfirmDialog(
            this,
            "Are you sure you want to delete "
                    + selectedProduct.getName() + "?",
            "Confirm Deletion",
            JOptionPane.YES_NO_OPTION);

    // Delete only if the user confirms
    if (confirmation == JOptionPane.YES_OPTION) {

        // Remove the product from its supplier catalog
        supplier.getProductCatalog()
                .removeProduct(selectedProduct);

        // Refresh the product table
        refreshTable();

        // Notify the user that deletion was successful
        JOptionPane.showMessageDialog(
                this,
                "Product deleted successfully!",
                "Success",
                JOptionPane.INFORMATION_MESSAGE);
    } 
        
    }//GEN-LAST:event_btnDeleteActionPerformed
